/**
 * Renders the Engapp mark to the PWA icon set and the Android app's launcher icon, themed
 * (monochrome) icon, notification icon and splash mark (android/app/src/main/res).
 *   node scripts/generate-icons.ts
 * Uses Playwright's Chromium (already a devDependency for e2e tests), so no image library
 * is added. Set CHROMIUM_PATH if the browser is not in Playwright's default location.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { E_PATH, markColors, markSvg, TICK_PATH } from '../src/ui/brand/mark.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
mkdirSync(join(pub, 'icons'), { recursive: true });

const favicon = markSvg({ tile: 'rounded' });
writeFileSync(join(pub, 'favicon.svg'), favicon + '\n');

// ------------------------------------------------------------------ Android (Capacitor)
// Adaptive icon: vector foreground (glyphs inside the 66/108 safe zone), the tile colour as
// the background layer, the same glyphs as the monochrome (themed icon) layer. Vector
// drawables take SVG path data; group transforms apply scale, then translate, like the SVG.
const res = join(root, 'android', 'app', 'src', 'main', 'res');
const ADAPTIVE_SCALE = 0.3;

function glyphGroups(scale: number, letter: string, tick: string): string {
  const tx = +(256 - 366 * scale).toFixed(2);
  const ty = +(280 + 247 * scale).toFixed(2);
  return (
    `  <group android:translateX="${tx}" android:translateY="${ty}" android:scaleX="${scale}" android:scaleY="-${scale}">\n` +
    `    <group android:translateY="-40">\n      <path android:fillColor="${tick}" android:pathData="${TICK_PATH}"/>\n    </group>\n` +
    `    <group android:translateX="176">\n      <path android:fillColor="${letter}" android:pathData="${E_PATH}"/>\n    </group>\n` +
    `  </group>\n`
  );
}

function vector(dp: number, scale: number, letter: string, tick: string): string {
  return (
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-icons.ts from src/ui/brand/mark.ts. Do not edit. -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${dp}dp" android:height="${dp}dp"\n` +
    `    android:viewportWidth="512" android:viewportHeight="512">\n` +
    glyphGroups(scale, letter, tick) +
    `</vector>\n`
  );
}

function writeRes(rel: string, text: string) {
  const file = join(res, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log('wrote android', rel);
}

writeRes(
  'drawable/ic_launcher_foreground.xml',
  vector(108, ADAPTIVE_SCALE, markColors.letter, markColors.tick),
);
writeRes('drawable/ic_launcher_monochrome.xml', vector(108, ADAPTIVE_SCALE, '#FFFFFFFF', '#FFFFFFFF'));
// Status-bar notification icon: white silhouette, glyphs filling the 24 dp box.
writeRes('drawable/ic_stat_engapp.xml', vector(24, 0.5, '#FFFFFFFF', '#FFFFFFFF'));
const adaptive =
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-icons.ts. Do not edit. -->\n` +
  `<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
  `    <background android:drawable="@color/ic_launcher_background"/>\n` +
  `    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n` +
  `    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n` +
  `</adaptive-icon>\n`;
writeRes('mipmap-anydpi-v26/ic_launcher.xml', adaptive);
writeRes('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive);
writeRes(
  'values/ic_launcher_background.xml',
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-icons.ts. Do not edit. -->\n<resources>\n    <color name="ic_launcher_background">${markColors.tile}</color>\n</resources>\n`,
);

/** The mark on a circular tile (legacy round launcher icon, Android 7.1). */
function roundSvg(): string {
  const glyphs = markSvg({ tile: 'none' }).replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">` +
    `<circle cx="256" cy="256" r="256" fill="${markColors.tile}"/>${glyphs}</svg>`
  );
}

const androidDensities: [string, number][] = [
  ['mdpi', 1],
  ['hdpi', 1.5],
  ['xhdpi', 2],
  ['xxhdpi', 3],
  ['xxxhdpi', 4],
];

const targets: { file: string; size: number; svg: string; dir?: string }[] = [
  { file: 'icons/icon-192.png', size: 192, svg: markSvg({ tile: 'rounded' }) },
  { file: 'icons/icon-512.png', size: 512, svg: markSvg({ tile: 'rounded' }) },
  // Maskable: full-bleed background, glyphs inside the 80 % safe circle.
  { file: 'icons/maskable-512.png', size: 512, svg: markSvg({ tile: 'square', scale: 0.34 }) },
  // iOS applies its own corner mask and ignores transparency.
  {
    file: 'icons/apple-touch-icon-180.png',
    size: 180,
    svg: markSvg({ tile: 'square', scale: 0.4 }),
  },
  // Legacy launcher icons (Android 7.x has no adaptive icons), 48 dp.
  ...androidDensities.flatMap(([d, f]) => [
    { file: `mipmap-${d}/ic_launcher.png`, size: 48 * f, svg: markSvg({ tile: 'rounded' }), dir: res },
    { file: `mipmap-${d}/ic_launcher_round.png`, size: 48 * f, svg: roundSvg(), dir: res },
  ]),
  // Splash mark for Android < 12 (drawable/splash.xml centres it on the canvas colour), 96 dp.
  { file: 'drawable-nodpi/splash_mark.png', size: 384, svg: markSvg({ tile: 'rounded' }), dir: res },
];

const browser = await chromium.launch(
  process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {},
);
const page = await browser.newPage({ deviceScaleFactor: 1 });
for (const { file, size, svg, dir = pub } of targets) {
  mkdirSync(dirname(join(dir, file)), { recursive: true });
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(
    `<html><body style="margin:0;background:transparent">${svg.replace('<svg ', `<svg width="${size}" height="${size}" `)}</body></html>`,
  );
  await page.screenshot({ path: join(dir, file), omitBackground: true });
  console.log('wrote', file);
}
await browser.close();
